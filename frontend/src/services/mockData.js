const getStored = (key, fallback) => {
  try {
    const raw = localStorage.getItem(`homeserve_store_${key}`);
    return raw ? JSON.parse(raw) : fallback;
  } catch {
    return fallback;
  }
};

const setStored = (key, value) => {
  try {
    localStorage.setItem(`homeserve_store_${key}`, JSON.stringify(value));
  } catch {
    // ignore storage quota errors
  }
  return value;
};

